#!/usr/bin/env python3
"""Builds Paper 1's tables and figure data from the evaluation results (standard library only).

    python3 eval/paper1_build.py            # writes docs/paper1/generated/

Inputs:
  eval/results/sync-sim-30min/seed-*-probes-{on,off}/   (cd app && SYNC_EVAL_MINUTES=30 SYNC_EVAL_SEEDS=5
                                                         SYNC_EVAL_OUT=../eval/results/sync-sim-30min npm run eval:sync)
  eval/results/paper1/delays.csv                          (cd app && PAPER1_DATA_OUT=../eval/results/paper1
                                                         npx vitest run test/paperData.test.ts)
Outputs (consumed by docs/paper1/paper1.tex; figures are drawn by pgfplots from the .dat files):
  table_main.tex, table_bias.tex, numbers.tex (\\newcommand macros for numbers quoted in the text),
  fig_pulse_error.dat, fig_delays.dat
"""
from __future__ import annotations

import csv
import json
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYNC = ROOT / "eval/results/sync-sim-30min"
DELAYS = ROOT / "eval/results/paper1/delays.csv"
OUT = ROOT / "docs/paper1/generated"

METHODS = ["first-offset", "windowed-min", "lower-hull", "lower-hull-transport"]
LABEL = {
    "first-offset": "First offset",
    "windowed-min": "Windowed minimum",
    "lower-hull": "Affine (lower hull)",
    "lower-hull-transport": "Affine + transport (ours)",
}


def reports(probes: str) -> list[dict]:
    dirs = sorted(SYNC.glob(f"seed-*-probes-{probes}"))
    if not dirs:
        raise SystemExit(f"no results in {SYNC} (see the docstring for how to produce them)")
    return [json.loads((d / "report.json").read_text()) for d in dirs]


def method(rep: dict, name: str) -> dict:
    return next(m for m in rep["methods"] if m["method"] == name)


def mean_sd(xs: list[float]) -> tuple[float, float]:
    return statistics.mean(xs), (statistics.stdev(xs) if len(xs) > 1 else 0.0)


def fmt(m: float, sd: float | None = None, bold: bool = False) -> str:
    s = f"{m:.2f}" + (f" $\\pm$ {sd:.2f}" if sd is not None else "")
    return f"\\textbf{{{s}}}" if bold else s


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    on, off = reports("on"), reports("off")
    seeds = len(on)

    # ---- Table I: cross-device error, probes on/off ---------------------------------------------------
    stats = {}
    for name in METHODS:
        pulse_on = [method(r, name)["pulsePairs"][0]["stats"]["rmseMs"] for r in on]
        pulse_off = [method(r, name)["pulsePairs"][0]["stats"]["rmseMs"] for r in off]
        p95_on = [method(r, name)["pulsePairs"][0]["stats"]["p95AbsMs"] for r in on]
        ptt_on = [method(r, name)["ptt"]["errorVsTruth"]["rmseMs"] for r in on]
        stats[name] = dict(pulse_on=mean_sd(pulse_on), pulse_off=mean_sd(pulse_off), p95_on=mean_sd(p95_on), ptt_on=mean_sd(ptt_on))
    best = min(METHODS, key=lambda n: stats[n]["pulse_on"][0])
    rows = []
    for name in METHODS:
        s = stats[name]
        b = name == best
        rows.append(
            f"{LABEL[name]} & {fmt(*s['pulse_on'], bold=b)} & {fmt(*s['pulse_off'])} & {fmt(s['p95_on'][0], bold=b)} & {fmt(*s['ptt_on'], bold=b)} \\\\"
        )
    (OUT / "table_main.tex").write_text(
        "% Generated by eval/paper1_build.py. Do not edit.\n"
        "\\begin{tabular}{lcccc}\n\\toprule\n"
        " & \\multicolumn{2}{c}{Pulse-pair RMSE (ms)} & p95 $|e|$ (ms) & PTT RMSE (ms) \\\\\n"
        "\\cmidrule(lr){2-3}\n"
        "Method & probes on & probes off & probes on & probes on \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # ---- Table II: per-device bias vs simulator truth (probes on) -------------------------------------
    def bias(rep: dict, name: str, dev: str) -> float:
        a = next(x for x in method(rep, name)["absolute"] if x["connection"].startswith(dev))
        return a["stats"]["meanMs"]

    brows = []
    for name in METHODS:
        a_on = mean_sd([bias(r, name, "Node A") for r in on])
        b_on = mean_sd([bias(r, name, "Node B") for r in on])
        b_off = mean_sd([bias(r, name, "Node B") for r in off])
        brows.append(f"{LABEL[name]} & {fmt(*a_on)} & {fmt(*b_on)} & {fmt(*b_off)} \\\\")
    (OUT / "table_bias.tex").write_text(
        "% Generated by eval/paper1_build.py. Do not edit.\n"
        "\\begin{tabular}{lccc}\n\\toprule\n"
        " & Node A (USB) & \\multicolumn{2}{c}{Node B (BLE)} \\\\\n\\cmidrule(lr){3-4}\n"
        "Method & probes on & probes on & probes off \\\\\n\\midrule\n" + "\n".join(brows) + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # ---- Figure: |pulse-pair error| over time, seed 1, probes on --------------------------------------
    series: dict[str, list[tuple[float, float]]] = {m: [] for m in METHODS}
    first = sorted(SYNC.glob("seed-*-probes-on"))[0]
    with open(first / "series.csv") as fh:
        for r in csv.DictReader(fh):
            if r["kind"] == "pulse" and r["method"] in series:
                series[r["method"]].append((float(r["t_s"]), abs(float(r["value_ms"]))))
    lines = ["t_min " + " ".join(m.replace("-", "_") for m in METHODS)]
    n = min(len(v) for v in series.values())
    step = max(1, n // 360)  # ~360 points per curve
    for i in range(0, n, step):
        t = series[METHODS[0]][i][0] / 60
        lines.append(f"{t:.3f} " + " ".join(f"{max(1e-3, series[m][i][1]):.4f}" for m in METHODS))
    (OUT / "fig_pulse_error.dat").write_text("\n".join(lines) + "\n")

    # ---- Figure: Node B one-way delay histogram in one 120 s estimator window ------------------------
    bins = 32  # 0.5 ms bins over 0-16 ms
    counts = {"samples": [0] * bins, "probe": [0] * bins}
    floors = {"samples": float("inf"), "probe": float("inf")}
    with open(DELAYS) as fh:
        for r in csv.DictReader(fh):
            if r["device"] != "B" or r["kind"] not in counts or float(r["t_s"]) >= 120:
                continue
            d = float(r["delay_ms"])
            floors[r["kind"]] = min(floors[r["kind"]], d)
            counts[r["kind"]][min(bins - 1, max(0, int(d * 2)))] += 1
    tot = {k: sum(v) for k, v in counts.items()}
    hl = ["delay_ms samples probe"] + [
        f"{i / 2:.2f} {counts['samples'][i] / tot['samples']:.5f} {counts['probe'][i] / tot['probe']:.5f}" for i in range(bins)
    ]
    (OUT / "fig_delays.dat").write_text("\n".join(hl) + "\n")

    # ---- numbers quoted in the text --------------------------------------------------------------------
    s = stats
    macros = {
        "NumSeeds": str(seeds),
        "BestRmse": f"{s['lower-hull-transport']['pulse_on'][0]:.2f}",
        "BestRmseNoProbes": f"{s['lower-hull-transport']['pulse_off'][0]:.2f}",
        "HullRmse": f"{s['lower-hull']['pulse_on'][0]:.2f}",
        "HullRmseNoProbes": f"{s['lower-hull']['pulse_off'][0]:.2f}",
        "MinRmse": f"{s['windowed-min']['pulse_on'][0]:.2f}",
        "FirstRmse": f"{s['first-offset']['pulse_on'][0]:.1f}",
        "BestPtt": f"{s['lower-hull-transport']['ptt_on'][0]:.2f}",
        "FirstPtt": f"{s['first-offset']['ptt_on'][0]:.1f}",
        "ProbeGain": f"{s['lower-hull-transport']['pulse_off'][0] / s['lower-hull-transport']['pulse_on'][0]:.1f}",
        "SamplesFloor": f"{floors['samples']:.2f}",
        "ProbeFloor": f"{floors['probe']:.2f}",
    }
    (OUT / "numbers.tex").write_text(
        "% Generated by eval/paper1_build.py. Do not edit.\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in macros.items())
    )
    print(f"wrote {OUT} ({seeds} seeds); best method {best}: {macros['BestRmse']} ms (probes off {macros['BestRmseNoProbes']} ms)")


if __name__ == "__main__":
    main()
