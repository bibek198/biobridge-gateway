#!/usr/bin/env python3
"""Builds Paper 2's tables from descriptor-synthesis runs (standard library only).

    python3 eval/paper2_build.py            # prints a summary, writes docs/paper2/generated/

Reads every eval/results/synth-*/<model>/<device>.json written by `npm run eval:synth` (SYNTH_LIVE=1).
A *condition* is (model, enabled oracles); runs of the same condition are pooled, the latest result per
device winning. Results that failed for infrastructure reasons (quota, network) are counted separately and
never as device outcomes.

Metrics per condition:
  correct          final descriptor matches the hidden ground truth on >= 99% of samples, every channel
  false accept     the verifier accepted a descriptor that is wrong   (the safety number)
  false reject     the final descriptor is right but the verifier never accepted it
  iterations       model requests until acceptance (or the budget)
  caught by        which oracle checks fired on rejected attempts
"""
from __future__ import annotations

import json
import statistics
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval/results"
OUT = ROOT / "docs/paper2/generated"

ORACLES = ["structural", "plausibility", "semantic", "cross-sensor"]
INFRA = ("QuotaExhaustedError", "TypeError: fetch failed", "APIConnection", "ApiError")


def condition(r: dict) -> str:
    on = [o for o in ORACLES if r.get("oracles", {}).get(o)]
    oracles = "all oracles" if len(on) == len(ORACLES) else ("validator only" if not on else "+".join(on))
    return f"{r['model']} | {oracles}"


def infra_failure(r: dict) -> bool:
    return bool(r.get("error")) and not r.get("final") and any(k in r["error"] for k in INFRA)


def load() -> dict[str, dict[str, dict]]:
    by_cond: dict[str, dict[str, dict]] = defaultdict(dict)
    files = sorted(RESULTS.glob("synth-*/*/*.json"), key=lambda p: p.stat().st_mtime)
    for f in files:
        r = json.loads(f.read_text())
        if "deviceId" not in r:
            continue
        by_cond[condition(r)][r["deviceId"]] = r  # later runs replace earlier ones
    return by_cond


def main() -> None:
    by_cond = load()
    if not by_cond:
        raise SystemExit("no synthesis results under eval/results/synth-*/")
    OUT.mkdir(parents=True, exist_ok=True)

    summary_rows, lines = [], []
    devices = sorted({d for c in by_cond.values() for d in c})
    for cond, results in sorted(by_cond.items()):
        valid = [r for r in results.values() if not infra_failure(r)]
        infra = len(results) - len(valid)
        scored = [r for r in valid if r.get("score")]
        correct = [r for r in scored if r["score"]["success"]]
        false_accept = [r for r in scored if r["accepted"] and not r["score"]["success"]]
        false_reject = [r for r in scored if not r["accepted"] and r["score"]["success"]]
        iters = [len(r["attempts"]) for r in valid]
        latency = [a["latencyMs"] / 1000 for r in valid for a in r["attempts"] if "latencyMs" in a]
        caught = Counter(f["oracle"] for r in valid for a in r["attempts"] if a["outcome"] == "rejected" for f in a.get("findings") or [])
        invalid = sum(1 for r in valid for a in r["attempts"] if a["outcome"] in ("invalid", "no-json"))

        lines.append(f"{cond}")
        lines.append(
            f"  devices {len(valid)} (+{infra} infra failures)  correct {len(correct)}/{len(scored)}  "
            f"false accept {len(false_accept)}  false reject {len(false_reject)}  "
            f"iterations mean {statistics.mean(iters) if iters else float('nan'):.2f}  "
            f"latency median {statistics.median(latency) if latency else float('nan'):.0f} s"
        )
        if caught or invalid:
            lines.append(f"  rejected attempts caught by: {dict(caught)}; invalid/no-JSON replies: {invalid}")
        for r in false_accept:
            bad = [c["channel"] for c in r["score"]["channels"] if c["fraction"] < 0.99]
            lines.append(f"  FALSE ACCEPT {r['deviceId']}: wrong channels {bad}")
        cond_tex = cond.replace("|", "&").replace("_", r"\_")
        summary_rows.append(
            f"{cond_tex} & {len(correct)}/{len(scored)} & {len(false_accept)} & {len(false_reject)} & "
            f"{(statistics.mean(iters) if iters else 0):.2f} & {(statistics.median(latency) if latency else 0):.0f} \\\\"
        )

    (OUT / "table_summary.tex").write_text(
        "% Generated by eval/paper2_build.py. Do not edit.\n"
        "\\begin{tabular}{llccccc}\n\\toprule\n"
        "Model & Oracles & Correct & False accept & False reject & Iterations & Latency (s) \\\\\n\\midrule\n"
        + "\n".join(summary_rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )

    # Per-device outcome matrix: ✓ correct, ✗ wrong, — not run / infra failure; superscript = iterations.
    conds = sorted(by_cond)
    head = " & ".join(c.split(" | ")[1] + " (" + c.split(" | ")[0].replace("gemini:", "").replace("claude-", "") + ")" for c in conds)
    rows = []
    for d in devices:
        cells = []
        for c in conds:
            r = by_cond[c].get(d)
            if r is None or infra_failure(r) or not r.get("score"):
                cells.append("--")
            else:
                mark = "\\checkmark" if r["score"]["success"] else "$\\times$"
                cells.append(f"{mark}$^{{{len(r['attempts'])}}}$")
        rows.append(f"\\texttt{{{d}}} & " + " & ".join(cells) + " \\\\")
    (OUT / "table_devices.tex").write_text(
        "% Generated by eval/paper2_build.py. Do not edit.\n"
        f"\\begin{{tabular}}{{l{'c' * len(conds)}}}\n\\toprule\nDevice & {head} \\\\\n\\midrule\n"
        + "\n".join(rows)
        + "\n\\bottomrule\n\\end{tabular}\n"
    )
    print("\n".join(lines))
    print(f"\nwrote {OUT}")


if __name__ == "__main__":
    main()
