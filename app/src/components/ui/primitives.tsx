export function TransportBadge({ kind }: { kind: string }) {
  const label = kind === "serial" ? "USB-serial" : kind === "ble" ? "BLE" : kind === "simulated" ? "Simulated link" : kind;
  return (
    <Badge tone="outline" icon={kind === "ble" ? "ble" : kind === "serial" ? "usb" : "sim"}>
      {label}
    </Badge>
  );
}

export function EmptyState({ icon = "info", title, children, action }: { icon?: IconName; title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="empty">
      <Icon name={icon} size={22} />
      <div className="e-title">{title}</div>
      {children && <div className="e-body">{children}</div>}
      {action}
    </div>
  );
}

export function Callout({ tone, icon, children }: { tone?: "warn" | "fail" | "ok" | "model"; icon?: IconName; children: ReactNode }) {
  return (
    <div className={`callout ${tone ?? ""}`} role={tone === "fail" ? "alert" : undefined}>
      <Icon name={icon ?? (tone === "fail" ? "alert" : tone === "ok" ? "check" : tone === "warn" ? "warn" : "info")} size={14} />
      <div>{children}</div>
    </div>
  );
}

/** Explains a term on hover or keyboard focus. */
export function Tip({ children, label, icon }: { children: ReactNode; label?: ReactNode; icon?: boolean }) {
  const id = useId();
  return (
    <span className={icon ? "tip icon-only" : "tip"} tabIndex={0} aria-describedby={id}>
      {icon ? <Icon name="info" size={12} /> : label}
      <span className="tip-body" role="tooltip" id={id}>
        {children}
      </span>
    </span>
  );
}

export function Tabs<T extends string>({ tabs, value, onChange }: { tabs: { id: T; label: ReactNode }[]; value: T; onChange: (id: T) => void }) {
  return (
    <div className="tabs" role="tablist">
      {tabs.map((t) => (
        <button key={t.id} role="tab" aria-selected={t.id === value} className={t.id === value ? "active" : ""} onClick={() => onChange(t.id)}>
          {t.label}
        </button>
      ))}
    </div>
  );
}

export function Segmented<T extends string>({ options, value, onChange, label }: { options: { id: T; label: ReactNode; title?: string }[]; value: T; onChange: (id: T) => void; label: string }) {
  return (
    <div className="btn-group" role="radiogroup" aria-label={label}>
      {options.map((o) => (
        <button
          key={o.id}
          role="radio"
          aria-checked={o.id === value}
          title={o.title}
          className={`btn small ${o.id === value ? "selected" : ""}`}
          onClick={() => onChange(o.id)}
        >
          {o.label}
        </button>
      ))}
    </div>
  );
}
