// Layout and status primitives. Every status is text (and usually an icon) on a tinted background:
// colour is never the only signal.

export function PageHeader({
  section,
  title,
  purpose,
  context,
  actions,
}: {
  section: string;
  title: string;
  purpose?: ReactNode;
  context?: ReactNode;
  actions?: ReactNode;
}) {
  return (
    <header className="page-header">
      <div>
        <div className="crumbs">{section}</div>
        <h1>{title}</h1>
        {purpose && <p className="purpose">{purpose}</p>}
        {context && <div className="context">{context}</div>}
      </div>
      {actions && <div className="actions">{actions}</div>}
    </header>
  );
}

export function Panel({
  title,
  sub,
  tools,
  children,
  flush,
  foot,
  className,
}: {
  title?: ReactNode;
  sub?: ReactNode;
  tools?: ReactNode;
  children?: ReactNode;
  flush?: boolean;
  foot?: ReactNode;
  className?: string;
}) {
  return (
    <section className={`panel ${className ?? ""}`}>
      {(title || tools) && (
        <div className="panel-head">
          {title && <h2>{title}</h2>}
          {sub && <span className="sub">{sub}</span>}
          {tools && <div className="tools">{tools}</div>}
        </div>
      )}
      <div className={flush ? "panel-body flush" : "panel-body"}>{children}</div>
      {foot && <div className="panel-foot">{foot}</div>}
    </section>
  );
}

export type Tone = "ok" | "warn" | "fail" | "live" | "muted" | "model" | "outline";

export function Metric({
  label,
  value,
  unit,
  sub,
  tone,
  tip,
}: {
  label: string;
  value: ReactNode;
  unit?: string;
  sub?: ReactNode;
  tone?: "ok" | "warn" | "fail";
  tip?: ReactNode;
}) {
  return (
    <div className={`metric ${tone ?? ""}`}>
      <div className="m-label">
        {label}
        {tip && <Tip icon>{tip}</Tip>}
      </div>
      <div className="m-value">
        {value}
        {unit && <span className="m-unit">{unit}</span>}
      </div>
      {sub && <div className="m-sub">{sub}</div>}
    </div>
  );
}

export function Badge({ tone, icon, children, title, pulse }: { tone: Tone; icon?: IconName; children: ReactNode; title?: string; pulse?: boolean }) {
  return (
    <span className={`badge ${tone}`} title={title}>
      {pulse && <span className="pulse" aria-hidden />}
      {icon && <Icon name={icon} size={12} />}
      {children}
    </span>
  );
}

export type DataSource = "simulated" | "hardware" | "replay";

const SOURCE: Record<DataSource, { tone: Tone; icon: IconName; label: string; title: string }> = {
  simulated: { tone: "model", icon: "sim", label: "Simulated", title: "Data generated by a software simulator, not measured on hardware" },
  hardware: { tone: "live", icon: "usb", label: "Hardware", title: "Data from a physical device" },
  replay: { tone: "muted", icon: "replay", label: "Replay", title: "Recorded bytes decoded again" },
};

export function SourceBadge({ source }: { source: DataSource }) {
  const s = SOURCE[source];
  return (
    <Badge tone={s.tone} icon={s.icon} title={s.title}>
      {s.label}
    </Badge>
  );
}

export function ModelledBadge() {
  return (
    <Badge tone="model" icon="info" title="Computed from a first-order model, not measured">
      Modelled
    </Badge>
  );
}

