// Generates the golden BioBridge frames shared by every implementation:
//   protocol/test-vectors.json               (app + Python tests)
//   firmware/test/test_bbframe/vectors.h      (firmware native tests)
// Run from app/: npm run gen:vectors

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { crc16CcittFalse } from "../src/protocol/frame.ts";
import {
  FrameType,
  NodeKind,
  frame,
  helloPayload,
  leadsOffPayload,
  nodeASamplesPayload,
  nodeBSamplesPayload,
  syncEventPayload,
} from "../src/protocol/nodes.ts";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");

const hex = (b: Uint8Array) => Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");

type Sample = { channel: string; value: number; deviceTimestampUs?: number };
type Vector = {
  name: string;
  descriptor: string;
  type: number;
  seq: number;
  device_ts_us: number;
  payload_hex: string;
  frame_hex: string;
  expect: { samples: Sample[]; info?: Record<string, number | string> };
};

const vectors: Vector[] = [];

function add(
  name: string,
  descriptor: string,
  type: number,
  seq: number,
  deviceTsUs: number,
  payload: Uint8Array,
  expect: Vector["expect"]
) {
  vectors.push({
    name,
    descriptor,
    type,
    seq,
    device_ts_us: deviceTsUs,
    payload_hex: hex(payload),
    frame_hex: hex(frame(type, seq, deviceTsUs, payload)),
    expect,
  });
}

const mac = [0x24, 0x6f, 0x28, 0xaa, 0xbb, 0xcc];

add(
  "node_a_hello",
  "biobridge-node-a",
  FrameType.HELLO,
  0,
  1_000,
  helloPayload({ nodeKind: NodeKind.NODE_A_ECG, sampleRateHz: 250, fwMajor: 0, fwMinor: 1, mac }),
  {
    samples: [],
    info: { protocol: 1, nodeKind: 1, sampleRateHz: 250, fwMajor: 0, fwMinor: 1, mac: "246f28aabbcc" },
  }
);

// Pin millivolts 1650 is the AD8232 mid-rail: (mv - 1650) / 100 = electrode mV.
add("node_a_samples", "biobridge-node-a", FrameType.SAMPLES, 1, 2_000_000, nodeASamplesPayload(4000, [1650, 1770, 1530, 1650]), {
  samples: [
    { channel: "ecg", value: 0, deviceTimestampUs: 2_000_000 },
    { channel: "ecg", value: 1.2, deviceTimestampUs: 2_004_000 },
    { channel: "ecg", value: -1.2, deviceTimestampUs: 2_008_000 },
    { channel: "ecg", value: 0, deviceTimestampUs: 2_012_000 },
  ],
});

add("node_a_leads_off", "biobridge-node-a", FrameType.LEADS_OFF, 2, 2_016_000, leadsOffPayload(0b10), {
  samples: [{ channel: "leadsOff", value: 2, deviceTimestampUs: 2_016_000 }],
});

add("node_a_sync_event", "biobridge-node-a", FrameType.SYNC_EVENT, 3, 2_020_123, syncEventPayload(1, 4), {
  samples: [{ channel: "syncEvent", value: 1, deviceTimestampUs: 2_020_123 }],
});

add(
  "node_b_samples",
  "biobridge-node-b",
  FrameType.SAMPLES,
  7,
  0xffff_ff00, // just before the u32 wrap, exercises unwrapping on the next frame
  nodeBSamplesPayload(10_000, [
    { red: 90_000, ir: 120_000 },
    { red: 89_500, ir: 119_000 },
  ]),
  {
    samples: [
      { channel: "ppg_red", value: 90_000, deviceTimestampUs: 0xffff_ff00 },
      { channel: "ppg_ir", value: 120_000, deviceTimestampUs: 0xffff_ff00 },
      { channel: "ppg_red", value: 89_500, deviceTimestampUs: 0xffff_ff00 + 10_000 },
      { channel: "ppg_ir", value: 119_000, deviceTimestampUs: 0xffff_ff00 + 10_000 },
    ],
  }
);

add(
  "node_b_hello",
  "biobridge-node-b",
  FrameType.HELLO,
  8,
  0x0000_2000, // wrapped: unwrapped value is 2^32 + 0x2000
  helloPayload({ nodeKind: NodeKind.NODE_B_PPG, sampleRateHz: 100, fwMajor: 0, fwMinor: 1, mac }),
  {
    samples: [],
    info: { protocol: 1, nodeKind: 2, sampleRateHz: 100, fwMajor: 0, fwMinor: 1, mac: "246f28aabbcc" },
  }
);

add("node_b_time_probe", "biobridge-node-b", FrameType.TIME_PROBE, 9, 0x0000_3000, new Uint8Array(0), { samples: [] });

const crcCheck = { ascii: "123456789", crc: crc16CcittFalse(new TextEncoder().encode("123456789")) };
if (crcCheck.crc !== 0x29b1) throw new Error(`CRC-16/CCITT-FALSE check failed: ${crcCheck.crc.toString(16)}`);

const json = {
  _comment: "Generated by app/scripts/gen-test-vectors.ts. Do not edit by hand.",
  crc_check: crcCheck,
  frames: vectors,
};
writeFileSync(resolve(repoRoot, "protocol/test-vectors.json"), JSON.stringify(json, null, 2) + "\n");

// C forbids empty initialisers; an empty payload gets one unused padding byte and an explicit length of 0.
const cBytes = (h: string) => (h.match(/../g) ?? ["00"]).map((b) => `0x${b}`).join(", ");
const header = `// Generated by app/scripts/gen-test-vectors.ts. Do not edit by hand.
#pragma once
#include <stdint.h>
#include <stddef.h>

typedef struct {
  const char *name;
  uint8_t type;
  uint16_t seq;
  uint32_t device_ts_us;
  const uint8_t *payload;
  size_t payload_len;
  const uint8_t *frame;
  size_t frame_len;
} bb_test_vector_t;

${vectors
  .map(
    (v, i) => `static const uint8_t v${i}_payload[] = {${cBytes(v.payload_hex)}};
static const uint8_t v${i}_frame[] = {${cBytes(v.frame_hex)}};`
  )
  .join("\n")}

static const bb_test_vector_t BB_TEST_VECTORS[] = {
${vectors
  .map(
    (v, i) =>
      `  {"${v.name}", ${v.type}, ${v.seq}, ${v.device_ts_us}u, v${i}_payload, ${v.payload_hex.length / 2}, v${i}_frame, ${v.frame_hex.length / 2}},`
  )
  .join("\n")}
};
static const size_t BB_TEST_VECTOR_COUNT = sizeof(BB_TEST_VECTORS) / sizeof(BB_TEST_VECTORS[0]);
`;
const headerPath = resolve(repoRoot, "firmware/test/test_bbframe/vectors.h");
mkdirSync(dirname(headerPath), { recursive: true });
writeFileSync(headerPath, header);

console.log(`wrote ${vectors.length} vectors`);
